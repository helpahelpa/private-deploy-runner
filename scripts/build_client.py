PRIVATE = Path(__file__).resolve().parents[1]
VENDOR = PRIVATE / 'local/trusted-tooling/client-build'
SHA = re.compile(r'[0-9a-f]{64}')
COMMIT = re.compile(r'[0-9a-f]{40}')
DIAGNOSTICS = None


def private_diagnostics(stdout, stderr):
    if DIAGNOSTICS is not None:
        with os.fdopen(os.open(DIAGNOSTICS, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600), 'ab') as stream:
            stream.write(stdout + b'\n' + stderr + b'\n')


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_json(path, value):
    Path(path).write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')


def sandbox_run(argv, *, timeout):
    """Own only the generated client-QA container, including CLI timeout paths."""
    if argv[:2] != ['docker', 'run'] or any(
            item in ('--name', '--cidfile') or item.startswith(('--name=', '--cidfile=')) for item in argv[2:]):
        raise ValueError('Sandbox identity must be generated by the trusted helper')
    identifier = uuid.uuid4().hex
    name = 'private-private-client-qa-' + identifier
    with tempfile.TemporaryDirectory(prefix='private-client-identity-') as directory:
        cidfile = Path(directory) / 'container.cid'
        command = [*argv[:2], '--cidfile', str(cidfile), '--name', name,
                   '--label', 'private.private-role=client-qa',
                   '--label', 'private.private-qa-id=' + identifier, *argv[2:]]
        try:
            return build_logs.run(command, timeout=timeout)
        finally:
            # Neither the identity directory nor the Docker socket is mounted
            # into source code. The unique name covers pre-CID startup failure.
            target = name
            if cidfile.is_file() and not cidfile.is_symlink():
                value = cidfile.read_text().strip()
                if re.fullmatch(r'[0-9a-f]{64}', value):
                    target = value
            try:
                cleanup = subprocess.run(['docker', 'rm', '--force', target], capture_output=True, timeout=10)
            except subprocess.TimeoutExpired:
                raise ValueError('Client sandbox cleanup exceeded its time limit') from None
            if cleanup.returncode and b'No such container:' not in cleanup.stderr:
                private_diagnostics(b'Client sandbox cleanup failed: ' + name.encode(), cleanup.stderr)
                raise ValueError('Client sandbox cleanup failed')
            cidfile.unlink(missing_ok=True)


def validate_bridge_classes(names):
    """Retain the reviewed builder's activity and compile-only-stub boundary."""
    if (not isinstance(names, list) or 'Lprivateworld/PrivateActivity;' not in names
            or any(not isinstance(name, str) or not name.startswith('Lprivateworld/') for name in names)):
        raise ValueError('Supplementary DEX contains a missing activity or non-bridge class/stub')
    return names


def execute(argv, **kwargs):
    argv = list(map(str, argv))
    result = (sandbox_run(argv, timeout=kwargs.get('timeout', 600)) if argv[:2] == ['docker', 'run']
              else subprocess.run(argv, capture_output=True, **kwargs))
    if result.returncode:
        # Source diagnostics and private endpoints must never enter runner logs.
        private_diagnostics(result.stdout, result.stderr)
        raise ValueError('Private client operation failed: ' + Path(str(argv[0])).name)
    return result.stdout


def checked_input(value):
    if not isinstance(value, dict) or set(value) != {'path', 'sha256'} or not SHA.fullmatch(value['sha256']):
        raise ValueError('Input requires an explicit path and SHA256 pin')
    path = Path(value['path'])
    if not path.is_file() or path.is_symlink() or digest(path) != value['sha256']:
        raise ValueError('Private build input fingerprint mismatch')
    return path.resolve()


def apk_download_credentials(config):
    """Pin the private packaging-only credential without decoding its contents."""
    value = config.get('apk_download_credentials')
    if value is None:
        return None
    path = checked_input(value)
    if path.stat().st_mode & 0o077:
        raise ValueError('APK download credential requires private file permissions')
    return path


def validate_build_mounts(config, inputs, vendor, credential):
    protected = [inputs[name] for name in ('key', 'cert')]
    if credential is not None:
        protected.append(credential)
        if credential.is_relative_to(vendor):
            raise ValueError('APK download credential must stay outside trusted tooling mounts')
    for tool in config.get('toolchains', []):
        if set(tool) != {'path', 'target'} or tool['target'] not in ('/toolchain/jdk', '/toolchain/dotnet', '/toolchain/android', '/toolchain/pwsh'):
            raise ValueError('Only explicit, read-only toolchain mounts are permitted')
        toolpath = Path(tool['path']).resolve()
        if not toolpath.is_dir() or any(path.is_relative_to(toolpath) for path in protected):
            raise ValueError('Toolchain mounts must exclude private packaging identity')


def validate_fixture_identity(original, key, credential):
    protected = {digest(path) for path in (key, credential) if path is not None}
    if digest(original) in protected:
        raise ValueError('Private packaging credentials must never enter test fixtures')


def verify_download_credential_payload(apk, credential, serializer):
    """Check the deliberate payload only in the post-test trusted packaging phase."""
    if credential is None:
        return
    expected = serializer(json.loads(credential.read_text()))
    with zipfile.ZipFile(apk) as packaged:
        try:
            actual = packaged.read('assets/privateworld/apk-download.properties')
        except KeyError:
            raise ValueError('Signed APK download authorization payload missing') from None
    if actual != expected:
        raise ValueError('Signed APK download authorization payload mismatch')


def snapshot(source, commit, destination, lfs_object_store=None):
    """Read Git blobs directly; no archive symlinks, hooks, filters or submodules."""
    if not COMMIT.fullmatch(commit):
        raise ValueError('An exact lowercase 40-character commit is required')
    resolved = execute(['git', '-C', source, 'rev-parse', '--verify', commit + '^{commit}']).decode().strip()
    if resolved != commit:
        raise ValueError('Commit mismatch')
    entries = execute(['git', '-C', source, 'ls-tree', '-rz', '--full-tree', commit]).split(b'\0')
    hashes = {}
    admitted = []
    for entry in entries:
        if not entry:
            continue
        header, raw_name = entry.split(b'\t', 1)
        mode, kind, oid = header.split()
        name = raw_name.decode('utf-8')
        parts = PurePosixPath(name)
        if parts.is_absolute() or '..' in parts.parts or '.git' in parts.parts or '\\' in name or '\x00' in name:
            raise ValueError('Unsafe source filename')
        if mode not in (b'100644', b'100755') or kind != b'blob':
            raise ValueError('Source must contain regular files only')
        admitted.append((name, oid.decode()))
    for (name, _), data in zip(admitted, git_source.read_blobs(source, [oid for _, oid in admitted])):
        lfs = re.fullmatch(rb'version https://git-lfs.github.com/spec/v1\noid sha256:([0-9a-f]{64})\nsize ([0-9]+)\n', data)
        if lfs:
            expected = lfs[1].decode()
            store = Path(lfs_object_store) if lfs_object_store else Path(source) / '.git/lfs/objects'
            candidates = [store / expected[:2] / expected[2:4] / expected, Path(source) / name]
            materialized = next((p for p in candidates if p.is_file() and not p.is_symlink()
                and p.stat().st_size == int(lfs[2]) and digest(p) == expected), None)
            if materialized is None:
                raise ValueError('Commit LFS object fingerprint mismatch or not provisioned')
            data = materialized.read_bytes()
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        hashes[name] = hashlib.sha256(data).hexdigest()
    return hashes


def production_sources(hashes):
    result = {}
    for name, value in hashes.items():
        path = PurePosixPath(name)
        accepted = ((path.parent.as_posix() == 'launch-build/multiplayer-client' and path.suffix == '.java'
                     and not path.stem.endswith('Test') and path.name != 'TlsProbe.java')
                    or (path.parent.as_posix() == 'launch-build/coop-client' and path.suffix == '.cs'))
        if accepted:
            # Response-file switches, whitespace/newlines and path escapes are forbidden.
            if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*\.(java|cs)', path.name):
                raise ValueError('Unsafe compiler input filename')
            result[name] = value
    if 'launch-build/multiplayer-client/PrivateActivity.java' not in result or not any(n.endswith('.cs') for n in result):
        raise ValueError('Complete Java and managed production source is required')
    return result


def apk_fingerprint(production, inputs, vendor, tools, config):
    # Test drivers, fixtures, test counts and asset-release allocations cannot
    # change installed native content. Packaging/compiler code remains pinned.
    tooling = {str(path.relative_to(vendor)): digest(path)
               for path in vendor.rglob('*') if path.is_file() and '__pycache__' not in path.parts
               and (path.parent.name in ('launch-build', 'server') or path.name in ('compile.py', 'csc.py'))}
    compiler_names = ('android', 'csc', 'dotnet', 'java', 'javac', 'r8')
    material_inputs = {name: digest(path) for name, path in inputs.items()}
    credential = apk_download_credentials(config)
    if credential is not None:
        material_inputs['apk_download_credentials'] = digest(credential)
    return native_apk.fingerprint(production, material_inputs,
        tooling, {name: digest(path) for name, path in tools.items() if name in compiler_names},
        {name: config['compile'][name] for name in compiler_names if name in config['compile']},
        config.get('connection'), config['image'])


def restore_native_payload(entry, destination):
    """Read only hash-verified cached APK data; no archive paths are extracted."""
    with zipfile.ZipFile(entry['path']) as apk:
        dex = apk.read('classes2.dex')
        helper = apk.read('assets/bin/Data/Managed/CoopRuntime.dll')
    (destination / 'classes.dex').write_bytes(dex)
    (destination / 'CoopRuntime.dll').write_bytes(helper)
    return dex


def container_command(config, mounts, command, writable=None, *, qa=False):
    image = config['image']
    if not re.fullmatch(r'sha256:[0-9a-f]{64}', image):
        raise ValueError('Client sandbox image must be pinned by immutable local image ID')
    argv = ['docker', 'run', '--rm', '--pull=never', '--network=none', '--read-only',
            '--user=1000:1000', '--cap-drop=ALL', '--security-opt=no-new-privileges',
            '--pids-limit=256', '--memory=' + ('2g' if qa else '4g'), '--cpus=' + ('2' if qa else '4'),
            '--tmpfs=/tmp:rw,nosuid,nodev,size=1g,mode=1777',
            '--tmpfs=/work:rw,nosuid,nodev,size=2g,mode=1777',
            '--tmpfs=/mnt:rw,nosuid,nodev,size=1g,mode=1777',
            '--tmpfs=/source/server/logs:rw,nosuid,nodev,size=64m,mode=1777',
            '--env=HOME=/tmp', '--env=PYTHONDONTWRITEBYTECODE=1',
            '--env=DOTNET_SYSTEM_GLOBALIZATION_INVARIANT=1',
            '--env=PYTHONPATH=' + config.get('python_dependencies', '/python-deps'),
            '--env=DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1', '--env=DOTNET_CLI_TELEMETRY_OPTOUT=1',
            '--env=DOTNET_NOLOGO=1', '--workdir=/work']
    for host, target in mounts:
        if ':' in str(host) or ',' in str(host) or not str(target).startswith('/'):
            raise ValueError('Invalid private sandbox mount')
        argv += ['--mount', f'type=bind,src={Path(host).resolve()},dst={target},readonly']
    if writable:
        argv += ['--mount', f'type=bind,src={Path(writable).resolve()},dst=/out']
    # Image ENTRYPOINT and image environment cannot select repository code.
    return argv + ['--entrypoint=python3', image, *command]


def verify_unchanged(pins):
    if any(digest(path) != expected for path, expected in pins.items()):
        raise ValueError('Frozen private input changed during build')


def qa_material(tree, fixtures, inputs, vendor, config, compiled):
    """All admitted source and readable mount bytes, deliberately conservative."""
    return {'schema': 3, 'source': component_inputs.identity(tree, 'client'), 'fixtures': fixtures,
        'inputs': {name: digest(path) for name, path in inputs.items()},
        'trusted': client_qa.tree_identity(vendor),
        'controller': {name: {'sha256': digest(PRIVATE / 'scripts' / name),
                              'mode': (PRIVATE / 'scripts' / name).stat().st_mode & 0o777} for name in
                       ('build_client.py', 'client_qa.py', 'client-qa-weights.json', 'qa_tasks.py', 'component_inputs.py',
                        'git_source.py', 'build_logs.py', 'native_apk.py')},
        'toolchains': {tool['target']: client_qa.tree_identity(tool['path'])
                       for tool in config.get('toolchains', [])},
        'config_sha256': client_qa.fingerprint({name: value for name, value in config.items() if name != 'qa_workers'}),
        'compiled': compiled}


def qa_identity(tree, fixtures, inputs, vendor, config, compiled):
    return client_qa.fingerprint(qa_material(tree, fixtures, inputs, vendor, config, compiled))


def qa_commands(commands, workers):
    if type(workers) is not int or not 1 <= workers <= 4:
        raise ValueError('Client QA workers must be between one and four')
    if commands == [['python3', '/trusted/regression.py']]:
        return [commands[0] + ['--shard-index', str(index), '--shard-count', str(workers)]
                for index in range(workers)]
    if workers != 1:
        raise ValueError('Parallel client QA requires the reviewed regression harness')
    return commands


def build(args):
    global DIAGNOSTICS
    build_started = time.monotonic()
    match = re.fullmatch(r'4\.2\.0\.([1-9][0-9]*)', args.version)
    if not match or not 62 <= int(match[1]) <= 2147483647:
        raise ValueError('Release version must be an allocated 4.2.0.N with N >= 62')
    output = Path(args.output).resolve()
    if output.exists():
        raise ValueError('Use a new output directory; release artifacts are immutable')
    config = json.loads(Path(args.config).read_text())
    force_full_qa = getattr(args, 'force_full_qa', False)
    if type(force_full_qa) is not bool:
        raise ValueError('Force full QA requires a boolean')
    workers = config.get('qa_workers', 1)
    vendor = Path(config.get('trusted_tooling', VENDOR)).resolve()
    if not vendor.is_dir() or vendor.is_symlink():
        raise ValueError('Provision the reviewed private client tooling snapshot')
    inputs = {name: checked_input(value) for name, value in config['inputs'].items()}
    required = {'base_apk', 'client_source', 'template', 'ca', 'key', 'cert',
                'helper', 'helper_manifest', 'android_receipt', 'mscorlib.dll', 'UnityEngine.dll', 'System.dll', 'LitJson.dll'}
    if not required <= inputs.keys():
        raise ValueError('Required private compilation/signing inputs are missing')
    credential = apk_download_credentials(config)
    validate_build_mounts(config, inputs, vendor, credential)
    trusted_pins = {str(path): digest(path) for path in vendor.rglob('*') if path.is_file() and '__pycache__' not in path.parts}
    for path in (Path(__file__),Path(client_qa.__file__),Path(component_inputs.__file__),
                 Path(git_source.__file__),Path(qa_tasks.__file__),client_qa.WEIGHTS):
        trusted_pins[str(path.resolve())] = digest(path)
    pins = {str(path): digest(path) for path in inputs.values()}
    if credential is not None:
        pins[str(credential)] = digest(credential)
    pins.update(trusted_pins)
    tool_pins = {name: checked_input(value) for name, value in config.get('toolchain_files', {}).items()}
    pins.update({str(path): digest(path) for path in tool_pins.values()})
    # Packaging identity and endpoint configs never enter test/compile mounts.
    commands = config.get('test_commands')
    if not isinstance(commands, list) or not commands or any(not isinstance(c, list) or not c or
            any(not isinstance(a, str) or '\x00' in a for a in c) for c in commands):
        raise ValueError('Operator-owned sandbox test commands are required')
    output.parent.mkdir(parents=True, exist_ok=True)
    DIAGNOSTICS = output.parent / (output.name + '.private.log')
    with tempfile.TemporaryDirectory(prefix='private-client-', dir=output.parent) as temp:
        stage = Path(temp)
        source = stage / 'source'
        source.mkdir()
        snapshot_started = time.monotonic()
        tree = snapshot(Path(args.source).resolve(), args.commit, source, config.get('lfs_object_store'))
        build_logs.emit('Client source preparation: ' + str(round(time.monotonic()-snapshot_started, 3)) + ' seconds.')
        qa_tree = component_inputs.client_source(tree)
        for name in tree.keys() - qa_tree.keys():
            (source / name).unlink()
        (source / 'server/logs').mkdir(parents=True, exist_ok=True)
        prod = production_sources(tree)
        apk_key = apk_fingerprint(prod, inputs, vendor, tool_pins, config)
        cache_root = config.get('apk_cache', str(Path(args.config).resolve().parent / 'signed-apk-cache'))
        store = native_apk.Store(cache_root, config.get('minimum_native_version_code', 1))
        with store.locked():
            reusable = store.lookup(apk_key)
        # Trusted builder structure contains only private code and admitted source DATA.
        root = stage / 'builder'
        shutil.copytree(vendor, root)
        for name in prod:
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source / name, target)
        (root / 'work/apk/managed').mkdir(parents=True)
        for name in ('mscorlib.dll', 'UnityEngine.dll', 'System.dll', 'LitJson.dll'):
            shutil.copyfile(inputs[name], root / 'work/apk/managed' / name)
        shutil.copyfile(inputs['template'], root / 'work/apk/md5_4201.bin')
        # Copy allowlisted fixtures. No external directory mount reaches test code.
        fixture_pins = {}
        for name, value in config.get('fixtures', {}).items():
            path = PurePosixPath(name)
            if path.is_absolute() or '..' in path.parts or '\\' in name or name in tree:
                raise ValueError('Fixture must be a new relative source path')
            original = checked_input(value)
            validate_fixture_identity(original, inputs['key'], credential)
            target = source / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(original, target)
            fixture_pins[name] = digest(original)
            pins[str(original)] = fixture_pins[name]
        compile_out = stage / 'compiled'
        compile_out.mkdir(mode=0o777)
        compile_out.chmod(0o777)
        compile_config = dict(config['compile'])
        write_json(root / 'compile.json', compile_config)
        common_mounts = [(vendor, '/trusted'),
                         (PRIVATE / 'scripts/client_qa.py', '/controller/client_qa.py'),
                         (client_qa.WEIGHTS, '/controller/client-qa-weights.json'),
                         *[(t['path'], t['target']) for t in config.get('toolchains', [])]]
        if reusable:
            build_logs.emit('Material APK inputs are unchanged; reusing the exact signed APK and native payload.')
            compiled_dex = restore_native_payload(reusable, compile_out)
        else:
            build_logs.emit('Android Java/managed compilation started in the restricted container.')
            execute(container_command(config, [*common_mounts, (root, '/builder')],
                                      ['/trusted/compile.py'], compile_out), timeout=600)
            compiled_dex = (compile_out / 'classes.dex').read_bytes()
        compiled_helper = compile_out / 'CoopRuntime.dll'
        # Preserve the established helper byte-for-byte whenever the source is identical.
        prior = json.loads(inputs['helper_manifest'].read_text())
        same_helper = all(prior.get('inputs', {}).get(n) == d for n, d in prod.items() if n.endswith('.cs'))
        same_helper = same_helper and all(prior.get('inputs', {}).get('work/apk/managed/' + name) == digest(inputs[name])
            for name in ('mscorlib.dll', 'UnityEngine.dll', 'System.dll', 'LitJson.dll'))
        same_helper = same_helper and prior.get('runtime_sha256') == digest(inputs['helper'])
        if same_helper and not reusable:
            shutil.copyfile(inputs['helper'], compiled_helper)
        helper_manifest = {'runtime_sha256': digest(compiled_helper),
                           'inputs': {n: d for n, d in prod.items() if n.endswith('.cs')}}
        write_json(compiled_helper.with_suffix('.build.json'), helper_manifest)
        test_config = stage / 'test-config'
        test_config.mkdir()
        write_json(test_config / 'config.json', compile_config)
        tests = []
        test_output = []
        partitioned = qa_commands(commands, workers)
        identity_started = time.monotonic()
        compiled_identity = {'dex': digest(compile_out / 'classes.dex'), 'managed': digest(compiled_helper)}
        qa_inputs = qa_material(tree, fixture_pins, inputs, vendor, config, compiled_identity)
        qa_key = client_qa.fingerprint(qa_inputs)
        build_logs.emit('Client broad QA input verification completed in ' + str(round(time.monotonic() - identity_started, 3)) + ' seconds.')
        qa_store = client_qa.Store(config.get('component_cache', str(Path(args.config).resolve().parent / 'client-qa-cache')))
        granular = None
        cached_qa = None
        required_ids = compile_config.get('required_test_ids', [])
        minimum_tests = compile_config.get('minimum_client_tests', 1)
        if commands == [['python3', '/trusted/regression.py']]:
            def invoke(command, mounted_source, overlays=()):
                result = sandbox_run(container_command(config,
                    [*common_mounts, (mounted_source, '/source'), *overlays, (test_config, '/trusted-test-config')],
                    ['/trusted/test.py', json.dumps(command)], qa=True), timeout=config.get('test_timeout', 1200))
                summary = client_qa.parse_result(result.stdout)
                if result.returncode or summary.get('passed') is not True:
                    private_diagnostics(result.stdout, result.stderr)
                    raise ValueError('Client module discovery or regression failed')
                return result, summary
            discovery_command = commands[0] + ['--discover-only']
            _, discovery = invoke(discovery_command, source)
            inventory = discovery.get('inventory')
            module_ids = qa_tasks.modules(inventory)
            if len(inventory) < minimum_tests or not set(required_ids) <= set(inventory):
                raise ValueError('Client module inventory is incomplete')
            views, keys = {}, {}
            for module in module_ids:
                readable = qa_tasks.client_inputs(source, qa_tree, module)
                material = dict(qa_inputs, module=module, test_ids=module_ids[module],
                                source={'source': readable, 'boundary': 'isolated client module'})
                if module in qa_tasks.BINARY_MODULES:
                    material['source'] = {'boundary': 'isolated binary transform', 'source': readable}
                    # These compiled outputs are never mounted into source QA.
                    material['compiled'] = {}
                    views[module] = (qa_tasks.materialize(source, stage / ('source-' + module),
                                                         dict(readable, **fixture_pins)), [])
                else:
                    view = qa_tasks.materialize(source, stage / ('source-' + module),
                        [name for name in readable if name.startswith('launch-build/')])
                    views[module] = (source, [(view / 'launch-build', '/source/launch-build')])
                keys[module] = client_qa.fingerprint(material)
            def execute_module(module, expected):
                command = commands[0] + ['--module', module]
                result, summary = invoke(command, *views[module])
                build_logs.emit('Client module ' + module + ': ' + str(summary.get('tests'))
                    + ' tests freshly executed in ' + str(summary.get('elapsed_seconds')) + ' seconds.')
                return ({'command': command, 'result': summary, 'exit_code': result.returncode,
                    'stdout_sha256': hashlib.sha256(result.stdout).hexdigest(),
                    'stderr_sha256': hashlib.sha256(result.stderr).hexdigest()},
                    result.stdout + b'\nSTDERR\n' + result.stderr)
            granular = qa_tasks.run(inventory, keys, qa_store, args.commit, execute_module,
                workers=workers, force=force_full_qa,
                weights=json.loads(client_qa.WEIGHTS.read_text())['seconds'], required=required_ids, minimum=minimum_tests)
            tests, test_output = granular['commands'], granular['logs']
            tested_source_commit = granular['tested_source_commit']
            cached_qa = granular if granular['reused'] else None
            for item in granular['modules']:
                if item['reused']:
                    build_logs.emit('Client module ' + item['module'] + ': cache hit; ' + str(item['tests'])
                        + ' passed at ' + item['tested_source_commit'][:12] + ', verified inputs unchanged.')
            build_logs.emit('Client module QA: ' + str(sum(item['reused'] for item in granular['modules']))
                + '/' + str(len(module_ids)) + ' cache hits; ' + str(granular['fresh_tests']) + ' tests freshly executed.')
        else:
            cached_qa = client_qa.load_cached(qa_store, qa_key, force_full_qa)
        if granular:
            pass
        elif cached_qa:
            build_logs.emit('Client broad QA cache hit; verified prior full-suite results reused; tests are not rerun.')
            tests, test_output = cached_qa['commands'], [cached_qa['log']]
            tested_source_commit = cached_qa['tested_source_commit']
        else:
            build_logs.emit('Client broad QA cache bypassed; full QA explicitly requested.' if force_full_qa
                            else 'Client broad QA cache miss; full regression suite started.')
            def run_partition(command):
                return sandbox_run(container_command(config,
                    [*common_mounts, (source, '/source'), (test_config, '/trusted-test-config')],
                    ['/trusted/test.py', json.dumps(command)], qa=True), timeout=config.get('test_timeout', 1200))
            results = client_qa.run_parallel(partitioned, workers, run_partition)
            for command, result in zip(partitioned, results):
                summary = client_qa.parse_result(result.stdout)
                build_logs.emit('Client QA worker '+str(summary.get('shard_index'))+': '
                    +str(summary.get('tests'))+' tests in '+str(summary.get('elapsed_seconds'))+' seconds.')
                tests.append({'command': command, 'result': summary, 'exit_code': result.returncode,
                              'stdout_sha256': hashlib.sha256(result.stdout).hexdigest(),
                              'stderr_sha256': hashlib.sha256(result.stderr).hexdigest()})
                test_output.append(result.stdout + b'\nSTDERR\n' + result.stderr)
                if result.returncode or not summary or not summary.get('passed'):
                    private_diagnostics(result.stdout, result.stderr)
                    raise ValueError('Exact-commit client sandbox regression failed')
            tested_source_commit = args.commit
        qa_totals = client_qa.validate_results(tests, required_ids, minimum_tests)
        # Retain expensive QA evidence even if a later packaging operation fails.
        # Reuse is admitted only after the same frozen-input checks as a complete
        # build; packaging, signing and live deployment still have their own gate.
        source_before = dict(qa_tree, **fixture_pins)
        if not cached_qa:
            verify_unchanged(pins)
            source_after = {name: digest(source / name) for name in source_before}
            if source_before != source_after or qa_identity(tree, fixture_pins, inputs, vendor, config, compiled_identity) != qa_key:
                raise ValueError('Frozen client QA dependencies changed during testing')
        qa_evidence = {'qa':qa_totals,'commands':tests,'input_sha256':qa_key,
                       'tested_source_commit':tested_source_commit,'reused':bool(cached_qa)}
        if granular:
            qa_evidence.update(modules=granular['modules'], fresh_tests=granular['fresh_tests'])
        evidence_path=output.parent/(output.name+'.qa.private.json')
        with os.fdopen(os.open(evidence_path,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600),'w') as stream:
            json.dump(qa_evidence,stream,sort_keys=True)
        if granular:
            qa_tasks.publish(qa_store, granular, args.commit)
        elif not cached_qa:
            with qa_store.locked():
                qa_store.publish(qa_key, args.commit, tests, b'\n'.join(test_output), required_ids, minimum_tests)
        # Source tests only see read-only source, copied fixtures and toolchain mounts.
        # The signer is loaded only after every test container has exited.
        sys.path[:0] = [str(root / 'launch-build'), str(root / 'server')]
        builder = importlib.import_module('prepare_multiplayer_client')
        builder.ROOT = root
        builder.LOCAL = stage / 'artifacts'
        builder.LOCAL.mkdir()
        from cryptography import x509
        from cryptography.hazmat.primitives import serialization
        cert = x509.load_pem_x509_certificate(inputs['cert'].read_bytes())
        certificate_sha256 = hashlib.sha256(cert.public_bytes(serialization.Encoding.DER)).hexdigest()
        # The lock covers the second lookup and durable version reservation.
        # Publication rechecks the cache after privacy/frozen-input validation;
        # concurrent operator prebuilds can never reuse a reserved version.
        with store.locked():
            reusable = store.lookup(apk_key)
            if reusable:
                compiled_dex = restore_native_payload(reusable, compile_out)
                metadata = reusable['metadata']
                if metadata['signing_cert_sha256'] != certificate_sha256:
                    raise ValueError('Cached APK signing identity differs from the pinned certificate')
                apk_version_code, apk_version_name = metadata['version_code'], metadata['version_name']
                same_helper = digest(compiled_helper) == digest(inputs['helper'])
                builder.signing_pair = lambda _: (_ for _ in ()).throw(ValueError('Reused APK must not be signed again'))
            else:
                import multiplayer_manifest
                with zipfile.ZipFile(inputs['base_apk']) as base:
                    base_version_code, _ = multiplayer_manifest.manifest_version(base.read('AndroidManifest.xml'))
                apk_version_code = store.reserve(base_version_code)
                apk_version_name = '4.2.0.' + str(apk_version_code)
                key = serialization.load_pem_private_key(inputs['key'].read_bytes(), password=None)
                if key.public_key().public_numbers() != cert.public_key().public_numbers():
                    raise ValueError('Persistent signing identity mismatch')
                builder.signing_pair = lambda _: (key, cert)
            helper_manifest['runtime_sha256'] = digest(compiled_helper)
            write_json(compiled_helper.with_suffix('.build.json'), helper_manifest)
            bridge_names = validate_bridge_classes(builder.dex_classes(compiled_dex))
            builder.compile_bridge = lambda scratch, receipt: (compiled_dex, [], bridge_names)
            def verify_signed(command):
                apk = Path(command[-1])
                java = compile_config['java']
                code = 'import subprocess; subprocess.run(' + repr([str(Path(java).parent / 'jarsigner'), '-verify', '/verify/client.apk']) + ',check=True,capture_output=True)'
                execute(container_command(config, [*common_mounts, (apk.parent, '/verify')], ['-c', code.replace('/verify/client.apk', '/verify/' + apk.name)]), timeout=120)
            builder.run = verify_signed
            connection = builder.connection_properties(config.get('connection'))
            connection_path = stage / 'connection.json'
            write_json(connection_path, config.get('connection'))
            package_args = SimpleNamespace(output=builder.LOCAL / 'client.apk', assets_root=builder.LOCAL / 'assets',
                version=args.version, apk_version_code=apk_version_code, apk_version_name=apk_version_name,
                base_apk=inputs['base_apk'], client_source=inputs['client_source'], ca=inputs['ca'],
                expected_ca_sha256=digest(inputs['ca']), toolchain=inputs['android_receipt'],
                coop_runtime=compiled_helper, connection_config=connection_path if config.get('connection') else None,
                apk_download_credentials=credential,
                require_existing_signing_identity=False,
                reuse_apk=reusable['path'] if reusable else None,
                reuse_apk_report=reusable['build_report'] if reusable else None)
            builder.build(package_args)
            build_report = json.loads((builder.LOCAL / 'client.build.json').read_text())
            manifest_tool = importlib.import_module('multiplayer_manifest')
            with zipfile.ZipFile(package_args.output) as packaged:
                actual_version = manifest_tool.manifest_version(packaged.read('AndroidManifest.xml'))
            if actual_version != (apk_version_code, apk_version_name):
                raise ValueError('Signed APK Android version differs from its build metadata')
            if credential is not None:
                verify_download_credential_payload(package_args.output, credential, builder.download_credentials)
            if reusable:
                if digest(package_args.output) != reusable['metadata']['sha256']:
                    raise ValueError('Reused signed APK bytes changed during asset preparation')
                apk_source_commit = reusable['source_commit']
            else:
                native_manifest = dict(build_report, apk_version_code=apk_version_code, apk_version_name=apk_version_name)
                portable_report = {name: native_manifest[name] for name in ('package', 'apk_sha256',
                    'apk_version_code', 'apk_version_name', 'classes_dex_original_unchanged',
                    'classes2_dex_sha256', 'signing_certificate_sha256')}
                apk_source_commit = args.commit
        build_logs.emit('Signed APK reused byte-for-byte.' if reusable else 'Android client packaged and signed successfully.')
        # Scan every decompressed entry for explicitly configured private route/credential strings.
        with zipfile.ZipFile(package_args.output) as apk:
            for entry in apk.infolist():
                raw = apk.read(entry)
                if any(secret.encode() in raw for secret in config.get('forbidden_apk_strings', []) if secret):
                    raise ValueError('Forbidden private route or credential data in APK')
        verify_unchanged(pins)
        source_before = dict(qa_tree, **fixture_pins)
        source_after = {name: digest(source / name) for name in source_before}
        if source_before != source_after:
            raise ValueError('Frozen sandbox source changed during testing')
        if qa_identity(tree, fixture_pins, inputs, vendor, config, compiled_identity) != qa_key:
            raise ValueError('Frozen client QA dependencies changed during build')
        if not reusable:
            with store.locked():
                existing = store.lookup(apk_key)
                if existing is None:
                    store.publish(apk_key, args.commit, package_args.output, native_manifest, portable_report)
                elif existing['metadata']['sha256'] != digest(package_args.output):
                    raise ValueError('Concurrent native APK publication differs')
        receipt = {'schema': 1, 'commit': args.commit, 'passed': True, 'source_files': tree,
                   'qa': dict(qa_totals, input_sha256=qa_key, tested_source_commit=tested_source_commit,
                              current_source_commit=args.commit, reused=bool(cached_qa),
                              force_full_qa=force_full_qa, workers=workers,
                              modules=granular['modules'] if granular else [],
                              fresh_tests=granular['fresh_tests'] if granular else (0 if cached_qa else qa_totals['tests']),
                              boundary='isolated client inputs, shared server production, fixtures, harness, configuration, tools and compiled payload'),
                   'production_sources': prod, 'fixture_sha256': fixture_pins, 'commands': tests,
                   'verified_apk': {'input_sha256': apk_key, 'source_commit': apk_source_commit,
                                    'sha256': digest(package_args.output), 'version_code': apk_version_code,
                                    'version_name': apk_version_name, 'reused': bool(reusable)},
                   'inputs_before': source_before, 'inputs_after': source_after,
                   'stable': source_before == source_after,
                   'sandbox': {'image': config['image'], 'network': 'none', 'read_only': True,
                               'user': '1000:1000', 'capabilities': [], 'signing_keys_mounted': False},
                   'completed_utc': datetime.datetime.now(datetime.timezone.utc).isoformat()}
        artifacts = builder.LOCAL
        # Replace original builder's machine-path-heavy report with portable provenance.
        build_report = json.loads((artifacts / 'client.build.json').read_text())
        (artifacts / 'client.build.json').unlink()
        write_json(artifacts / 'client-tests.json', receipt)
        with os.fdopen(os.open(artifacts / 'tests.private.log', os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'wb') as stream:
            stream.write(b'\n'.join(test_output))
        asset_hashes = {str(p.relative_to(artifacts / 'assets')): digest(p)
                        for p in sorted((artifacts / 'assets').rglob('*')) if p.is_file()}
        manifest = {'schema': 1, 'status': 'TESTED_NOT_DEPLOYED', 'commit': args.commit,
                    'version': args.version, 'package': build_report['package'],
                    'apk': 'client.apk', 'apk_sha256': digest(artifacts / 'client.apk'),
                    'apk_version_code': apk_version_code, 'apk_version_name': apk_version_name,
                    'apk_input_sha256': apk_key, 'apk_source_commit': apk_source_commit,
                    'apk_reused': bool(reusable),
                    'assets': 'assets', 'asset_files': asset_hashes,
                    'client_tests_receipt': 'client-tests.json', 'client_tests_sha256': digest(artifacts / 'client-tests.json'),
                    'build_inputs': prod,
                    'private_input_sha256': {name: digest(path) for name, path in inputs.items() if name != 'key'},
                    'toolchain_sha256': {name: digest(path) for name, path in tool_pins.items()},
                    'trusted_builder_sha256': {str(p.relative_to(PRIVATE)): expected for name, expected in sorted(trusted_pins.items()) for p in [Path(name)]},
                    'classes_dex_original_unchanged': build_report['classes_dex_original_unchanged'],
                    'classes2_dex_sha256': build_report['classes2_dex_sha256'],
                    'signing_certificate_sha256': build_report['signing_certificate_sha256'],
                    'runtime_sha256': digest(compiled_helper), 'established_helper_preserved': same_helper,
                    'connection_properties_sha256': hashlib.sha256(connection).hexdigest()}
        update_manifest = native_apk.update_metadata(manifest, artifacts / 'client.apk')
        write_json(artifacts / 'assets/apk-update.json', update_manifest)
        manifest['asset_files']['apk-update.json'] = digest(artifacts / 'assets/apk-update.json')
        write_json(artifacts / 'manifest.json', manifest)
        artifacts.rename(output)
        build_logs.emit('Client component complete: ' + str(round(time.monotonic()-build_started, 3)) + ' seconds.')
        return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('config', 'source', 'commit', 'output', 'version'):
        parser.add_argument('--' + name, required=True)
    parser.add_argument('--force-full-qa', action='store_true', help='Run the entire client regression suite even when broad inputs match')
    try:
        result = build(parser.parse_args())
    except (ValueError, KeyError, OSError, subprocess.TimeoutExpired) as error:
        # Never format private config/paths or source-supplied subprocess output.
        parser.exit(1, 'Client build failed (' + type(error).__name__ + '). See private operator diagnostics.\n')
    print(json.dumps(result, sort_keys=True))


if __name__ == '__main__':
    main()
